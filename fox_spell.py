def _build():
    m = {}
    correct = set(_CORRECT)
    real = correct | _REAL_EXTRA
    for w in _CORRECT:
        if len(w) < 4:
            continue
        for i, ch in enumerate(w):
            g = _G_OF.get(ch)
            if not g:
                continue
            for other in g:
                if other == ch:
                    continue
                v = w[:i] + other + w[i + 1:]
                if v not in real:
                    m.setdefault(v, w)
    for right, wrongs in _EXPLICIT.items():
        for wr in wrongs.split():
            m[wr] = right
    for stem in _TANVIN:
        m.setdefault(stem + 'ن', _TANVIN_FIX[stem])
    for k in list(m):
        if k in real:
            del m[k]
    return m


TYPO_MAP = _build()
_SUFFIXES = sorted(['ها', 'های', 'هایی', 'ان', 'ات', 'ی', 'ای', 'ام', 'ت', 'ش', 'م', 'تر', 'ترین', 'مان', 'تان', 'شان', 'ه'],
                   key=len, reverse=True)
_LETTERS = re.compile(r'[\u0622-\u063A\u0641-\u064A\u067E\u0686\u0698\u06A9\u06AF\u06CC\u200c]+')
_SKIP = re.compile(r'https?://\S+|www\.\S+|[@#/]\w+|\S*[A-Za-z0-9۰-۹]\S*')


def _fix_word(w):
    if w in TYPO_MAP:
        return TYPO_MAP[w]
    for suf in _SUFFIXES:
        if w.endswith(suf):
            stem = w[:-len(suf)].rstrip('\u200c')
            if len(stem) >= 3 and stem in TYPO_MAP:
                right = TYPO_MAP[stem]
                if right.endswith('ً') or ' ' in right:      # «حتماً» + پسوند و عبارت‌های چندکلمه‌ای رو دست نمی‌زنیم
                    return None
                return right + ('\u200c' if suf in ('ها', 'های', 'هایی', 'ای', 'تر', 'ترین') else '') + suf
    return None


def find_typos(text, limit=3):
    """[(غلط، درست), ...] — فقط غلط‌های مطمئن؛ حداکثر limit تا."""
    if not text or len(text) > 600:
        return []
    clean = _DIAC.sub('', _SKIP.sub(' ', text.translate(_AR)))
    out = []; seen = set()
    for m in _LETTERS.finditer(clean):
        tok = m.group(0).strip('\u200c')
        if len(tok) < 3 or tok in seen:
            continue
        seen.add(tok)
        right = _fix_word(tok)
        if right and right != tok:
            out.append((tok, right))
            if len(out) >= limit:
                break
    return out


def format_typos(pairs):
    lines = "\n".join(f"• «{w}» ← «{r}»" for w, r in pairs)
    return f"✍️ املای درستش این‌طوریه 🦊\n{lines}"
