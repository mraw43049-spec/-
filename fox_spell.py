"""
غلط‌گیر املایی + پیشنهاد دستور — کاملاً آفلاین (بدون API و بدون اینترنت).

۱) suggest_command(text, phrases)  → «آیا منظورت X بود؟»  (گازینو → کازینو)
   مقایسه‌ی «آوایی» (گ/ک، ق/غ، ذ/ز/ض/ظ، ث/س/ص، ط/ت، ح/ه، ع/ا، پ/ب، چ/ج) + فاصله‌ی ویرایشی.
۲) find_typos(text)               → [(غلط، درست), ...]
   فقط غلط‌های «مطمئن»: فهرست دستی غلط‌های رایج + نسخه‌های غلطِ تولیدشده از املای درست کلمه‌های پرکاربرد
   (قذا → غذا، ازیت → اذیت، حوسله → حوصله ...). کلمه‌ی عامیانه (مثل «میخوام») غلط حساب نمی‌شه.
"""
import re

_AR = str.maketrans({'ي': 'ی', 'ى': 'ی', 'ك': 'ک', 'ة': 'ه', 'ۀ': 'ه', 'أ': 'ا', 'إ': 'ا', 'ٱ': 'ا'})
_DIAC = re.compile(r'[\u064B-\u065F\u0670\u0640]')


# ═══════════════════════ ۱) پیشنهاد دستور ═══════════════════════

def norm_cmd(text):
    """متن → حروف/عدد با فاصله‌ی ساده (ایموجی، علامت، نیم‌فاصله و اعراب حذف می‌شه)."""
    t = _DIAC.sub('', (text or '').translate(_AR)).lower().replace('\u200c', ' ')
    t = re.sub(r'[^\w\u0600-\u06FF\s]', ' ', t)
    return re.sub(r'\s+', ' ', t).strip()


_PH = str.maketrans({'گ': 'ک', 'غ': 'ق', 'ذ': 'ز', 'ض': 'ز', 'ظ': 'ز', 'ث': 'س', 'ص': 'س', 'ط': 'ت', 'ح': 'ه',
                     'ع': 'ا', 'آ': 'ا', 'ء': '', 'ئ': 'ی', 'ؤ': 'و', 'پ': 'ب', 'چ': 'ج', 'ژ': 'ز'})


def phonetic(t):
    """حروف هم‌صدا یکی می‌شن و حرف‌های تکراری جمع می‌شن (کازینوو → کازینو، گازینو → کازینو)."""
    return re.sub(r'(.)\1+', r'\1', t.translate(_PH))


def edit_distance(a, b, limit=2):
    """فاصله‌ی ویرایشی (با جابه‌جایی دو حرف کنار هم). اگه از limit بیشتر شد limit+1 برمی‌گردونه."""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    prev2 = None
    prev = list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            c = 0 if a[i - 1] == b[j - 1] else 1
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + c)
            if prev2 is not None and i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                cur[j] = min(cur[j], prev2[j - 2] + 1)
        if min(cur) > limit:
            return limit + 1
        prev2, prev = prev, cur
    return prev[-1]


_CALLS = ('روباهیو', 'روباه جون', 'روباه', 'روبی')


def _best(t, phrases, known):
    tp = phonetic(t)
    best = None
    for p, pn in phrases:
        pp = phonetic(pn)
        core = len(pp.replace(' ', ''))
        if core < 4 or abs(len(tp) - len(pp)) > 2:
            continue
        if tp == pp:
            cand = (0, len(pn), p)                        # فقط هم‌صدا/تکرار حرف: مطمئن‌ترین حالت
        else:
            lim = 2 if core >= 10 else 1 if core >= 6 else 0
            if not lim or edit_distance(tp, pp, lim) > lim:
                continue
            if tp.startswith(pp) or pp.startswith(tp):    # «شهرداری» به‌جای «شهردار»: احتمالاً کلمه‌ی دیگه‌ست
                continue
            cand = (edit_distance(tp, pp, lim), len(pn), p)
        if best is None or cand < best:
            best = cand
    return best[2] if best else None


def suggest_command(text, phrases):
    """اگه کل پیام شبیه (ولی نه دقیقاً) یکی از دستورها بود، همون دستور رو برمی‌گردونه؛ وگرنه None.
    phrases: لیست دستورهای درست (مثل «کازینو روبی»). پیام‌های طولانی/جمله‌ای هیچ‌وقت پیشنهاد نمی‌گیرن."""
    t = norm_cmd(text)
    if not t or len(t) > 40 or len(t.split()) > 4:
        return None
    pl = [(p, norm_cmd(p)) for p in phrases]
    known = {pn for _, pn in pl}
    if t in known:
        return None
    r = _best(t, pl, known)
    if r:
        return r
    for c in _CALLS:                                     # «روباهیو گازینو»
        if t.startswith(c + ' '):
            rem = t[len(c) + 1:].strip()
            if rem and rem not in known:
                return _best(rem, pl, known)
            return None
    return None


_TRANSFER_RE = re.compile(r'(\S+(?:\s+\S+){1,2})\s+([0-9۰-۹][0-9۰-۹.,]*(?:k|کی|کا|m|م|میل)?)', re.I)


def suggest_transfer(text):
    """«انتقال روپ پوینت 50» → «انتقال روب پوینت 50»"""
    m = _TRANSFER_RE.fullmatch((text or '').strip())
    if not m:
        return None
    head = norm_cmd(m.group(1)); target = 'انتقال روب پوینت'
    if head == target or len(head) > 30:
        return None
    if phonetic(head) == phonetic(target) or edit_distance(phonetic(head), phonetic(target), 2) <= 2:
        return f"{target} {m.group(2)}"
    return None


